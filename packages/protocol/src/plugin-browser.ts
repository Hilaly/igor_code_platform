/**
 * Браузерная часть плагина как контракт (docs/ui-extension-model.md): по каким адресам лежит
 * собранный код и через что он получает singleton-зависимости хоста.
 *
 * Живёт в протоколе, а не в демоне: адрес составляет демон, а разбирает браузер, и реестр модулей
 * заполняет веб-приложение, тогда как список спецификаторов задаёт сборка в демоне. Разъехавшиеся
 * половины дали бы либо 404, либо второй экземпляр React — то и другое ловится компилятором только
 * при одном источнике правды.
 */

/**
 * Ключ глобального объекта «спецификатор → модуль». Именно глобальный объект, а не import map:
 * карту пришлось бы вписывать в `index.html` до первого модульного скрипта и вести отдельно для
 * dev и прода, а собранный так бандл нельзя было бы импортировать из Node, то есть проверить без
 * живого браузера (docs/ui-extension-model.md, «Почему так»).
 */
export const hostModuleRegistryKey = "__sovereignHostModules__";

/**
 * Модули, которые плагин обязан брать у хоста, а не привозить свои. React — потому что два
 * экземпляра ломают хуки; кит — потому что его классы CSS Modules захешированы под сборку хоста, и
 * копия кита в бандле плагина осталась бы без стилей.
 */
export const hostModuleSpecifiers = [
  "react",
  "react-dom",
  "react-dom/client",
  "react/jsx-runtime",
  "react/jsx-dev-runtime",
  "@sovereign/ui-kit",
] as const;

export type HostModuleSpecifier = (typeof hostModuleSpecifiers)[number];

/** Общий префикс адресов собранного браузерного кода плагина. */
export const pluginAssetPrefix = "/plugin-assets";

/** Строка таблицы маршрутов демона под эти адреса. Рядом с адресом, чтобы они не разъехались. */
export const pluginAssetPathPattern = `${pluginAssetPrefix}/:pluginKey/:revision/:file`;

/**
 * Имена файлов, на которые ссылается статус плагина. Рядом с ними сборка кладёт карты кода
 * (`browser.js.map`, `browser.css.map`), но по имени их никто не спрашивает: браузер приходит за
 * ними по ссылке из самого файла.
 *
 * Выход сборки плоский — одна точка входа, никакого code splitting, мелкие ассеты инлайнятся. Это
 * не побочность, а условие того, что в адресе хватает одного сегмента файла.
 */
export const pluginBrowserFileNames = {
  script: "browser.js",
  styles: "browser.css",
} as const;

/**
 * Адрес файла собранного бандла. Ревизия в пути, а не в query: она делает адрес неизменяемым, и
 * ответ можно отдавать с `immutable` — новая сборка это новый адрес, а не новая версия старого.
 *
 * Ключ плагина кодируется: в нём есть двоеточия (`project:<проект>:<id>`), и без кодирования
 * сегмент читался бы неоднозначно.
 */
export function pluginAssetAddress(pluginKey: string, revision: string, file: string): string {
  return `${pluginAssetPrefix}/${encodeURIComponent(pluginKey)}/${encodeURIComponent(revision)}/${encodeURIComponent(file)}`;
}

/**
 * Где лежит собранный браузерный код работающего плагина. Адреса готовые, а не части, из которых
 * их надо собрать: собирает их тот, кто знает ревизию, — иначе браузер повторял бы правило
 * составления адреса и расходился бы с демоном при первой же его правке.
 */
export type PluginBrowserAssets = {
  revision: string;
  /** Адрес модуля-точки входа. */
  entry: string;
  /** Адрес таблицы стилей; её нет у плагина, не написавшего ни одного CSS-файла. */
  styles?: string;
};
