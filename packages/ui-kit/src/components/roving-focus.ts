/**
 * Перебор доступных элементов по кругу — общий счёт для вкладок и меню. Оба держат фокус на одном
 * элементе набора и переставляют его стрелками, различаясь только разметкой; правило же одно, и
 * второй его экземпляр разошёлся бы с первым на первом же исправлении.
 *
 * Функция ничего не знает про DOM: набор приходит массивом, а значит порядок известен из данных, а не
 * из документа. Это отдельная точка проверки — единственная логика вкладок и меню, которую видно без
 * браузера.
 */

/** Элементу нужен только признак недоступности: остальные поля набора здесь не при чём. */
export type RovingItem = {
  disabled?: boolean;
};

/**
 * Индекс доступного элемента, если шагать от `from` на `step` по кругу; `undefined` — доступных нет.
 *
 * `from` вне границ набора — законный вход: `-1` со шагом `+1` даёт первый доступный элемент, а
 * `items.length` со шагом `-1` — последний. Так «домой» и «в конец» выражаются той же функцией, что
 * и стрелки, вместо двух отдельных проходов по массиву.
 */
export function nextEnabledIndex(
  items: readonly RovingItem[],
  from: number,
  step: number,
): number | undefined {
  const total = items.length;

  for (let offset = 1; offset <= total; offset += 1) {
    // Двойной остаток: `%` в JavaScript сохраняет знак делимого, а нам нужен индекс массива.
    const index = (((from + step * offset) % total) + total) % total;

    if (items[index]?.disabled !== true) {
      return index;
    }
  }

  return undefined;
}
