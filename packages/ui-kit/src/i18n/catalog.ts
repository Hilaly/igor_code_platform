/**
 * Каталог сообщений адресуется парой «неймспейс и локаль» (docs/ui-kit.md). Ядро владеет своим
 * неймспейсом, плагин — своим, и плагин имеет право поставить каталог **для нашего** неймспейса: так
 * на платформе появляется новый язык интерфейса.
 *
 * Каталоги — данные. Ни функций, ни компиляции сообщений здесь нет: форматирование идёт через `Intl`
 * (docs/ui-kit.md), а зависимость на библиотеку интернационализации попала бы в публичный контракт кита.
 */

/**
 * Неймспейс ядра. Плагин не может его занять, но может прислать для него каталог. Объявлен в
 * протоколе, потому что вклад «каталог локали» проверяет демон (docs/plugins.md), а два объявления
 * одного неймспейса разошлись бы на первой же правке.
 */
export { coreCatalogNamespace as coreNamespace } from "@sovereign/protocol";

/** Базовая локаль. Ключи и исходные строки на английском, как и весь код. */
export const baseCatalogLocale = "en";

export type Catalog = Record<string, string>;

export type CatalogRegistration = {
  namespace: string;
  /** Тег локали для `Intl`: `en`, `ru`, `pt-BR`. */
  locale: string;
  messages: Catalog;
};
