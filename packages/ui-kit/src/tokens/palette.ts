/**
 * Палитра — замороженная часть визуального контракта (ADR-0031). Её задаёт цветовая схема, и именно
 * поэтому значений здесь мало: добавление ключа ломает все существующие схемы, а добавление роли —
 * ничего.
 *
 * Это один из двух файлов, где цветовые литералы разрешены: линтер запрещает их всюду, кроме
 * `src/tokens/**` (eslint.config.js).
 */

export const paletteKeys = [
  /** Фон страницы. */
  "surface",
  /** Поднятая поверхность: панели, карточки, всплывающие слои. */
  "surfaceRaised",
  /** Утопленная поверхность: полосы списков, поля ввода. */
  "surfaceSunken",
  /** Линии: границы панелей, разделители. */
  "border",
  /** Основной текст. */
  "ink",
  /** Второстепенный текст: подписи, единицы, пояснения. */
  "inkMuted",
  /** Акцент: выделенное действие, фокус, выбранная строка. */
  "accent",
  /** Текст поверх акцента. */
  "accentInk",
  /** Опасность: удаление, отказ, упавший плагин. */
  "danger",
  /** Текст поверх опасности. */
  "dangerInk",
  /** Предупреждение: работает, но не так, как задумано. */
  "warning",
  /** Успех: доехало, поднялось, применилось. */
  "success",
  /** Затемнение под модальным слоем; значение с прозрачностью. */
  "overlay",
] as const;

export type PaletteKey = (typeof paletteKeys)[number];

export type Palette = Record<PaletteKey, string>;

export const paletteVariants = ["light", "dark"] as const;

/** Вариант палитры. Выбор пользователя включает ещё «системный», но палитр всё равно две. */
export type PaletteVariant = (typeof paletteVariants)[number];

export type PaletteSet = Record<PaletteVariant, Palette>;
