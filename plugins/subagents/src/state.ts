/**
 * Состояние субагента (docs/subagents.md).
 *
 * Отдельным модулем, а не внутри `registry.ts`, потому что его читают **обе** половины плагина:
 * воркер и панель. Реестр тянет `storage` из серверного SDK, и панель, импортировав его ради одного
 * значения, утащила бы этот SDK в браузерный бандл.
 */

/**
 * Чем кончилась работа субагента.
 *
 * `starting` — задание отправлено, но платформа ещё не ответила, что приняла его. Состояние живёт
 * доли секунды и существует ради одного: пока оно стоит, простой сессии **не** значит «отработал».
 * Иначе обход, разбуженный созданием сессии, объявил бы субагента закончившим до того, как тот
 * начал.
 */
export type SubagentState = "starting" | "running" | "finished" | "failed" | "stopped";

/** Субагент, работа которого ещё не кончилась. */
export function isWorking(state: SubagentState): boolean {
  return state === "starting" || state === "running";
}
