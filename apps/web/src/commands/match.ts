/**
 * Совпадение набранного с заголовком команды. Отдельным модулем, потому что это единственное правило
 * палитры, у которого есть спорные случаи, — и проверяется он без React.
 */

/**
 * Каждое слово запроса обязано найтись в заголовке; порядок слов не важен. Подстроки хватает: набрав
 * «пан скр», человек ждёт «Скрыть левую панель», и требовать точный порядок значило бы заставить его
 * помнить формулировку целиком. Нечёткого совпадения по буквам здесь нет намеренно: на двенадцати
 * командах оно даёт больше ложных строк, чем находит.
 *
 * Пустой запрос совпадает со всем: палитра открывается полным оглавлением.
 */
export function matchesQuery(query: string, title: string): boolean {
  const haystack = title.toLocaleLowerCase();

  return query
    .toLocaleLowerCase()
    .split(/\s+/)
    .filter((word) => word !== "")
    .every((word) => haystack.includes(word));
}
