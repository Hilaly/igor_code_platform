/**
 * Запись файла в директории данных (docs/data-directory.md). Потребителей три: настройки, учётная
 * запись и сессии входа, — и все три обязаны переживать обрыв записи, потому что оборванная запись
 * настроек ломает старт, а оборванная запись сессий выкидывает человека из интерфейса.
 */

import { renameSync, unlinkSync, writeFileSync } from "node:fs";

/**
 * Замена целиком, а не дописывание: наблюдатель директории не должен увидеть половину файла, а
 * оборванная на середине запись не должна оставить файл битым (docs/data-directory.md).
 *
 * Режим `0600` — часть механизма: рядом с настройками лежат хеш пароля и хеши токенов сессий.
 *
 * Байты, а не только текст: тем же способом кладётся бутстрап воркера из нагрузки артефакта
 * (docs/toolchain.md), а он приезжает уже собранным. Кодировка при этом игнорируется — она
 * относится только к строке.
 */
export function writeFileAtomically(path: string, text: string | Uint8Array): void {
  const temporary = `${path}.${process.pid}.tmp`;

  try {
    writeFileSync(temporary, text, { encoding: "utf8", mode: 0o600 });
    renameSync(temporary, path);
  } catch (cause) {
    // Временный файл в директории данных пережил бы перезапуск и остался бы мусором; удалить его не
    // удалось только если его и не создали.
    try {
      unlinkSync(temporary);
    } catch {
      // Нечего убирать.
    }

    throw cause;
  }
}
