/**
 * Шов между разработкой и продакшн-артефактом (docs/toolchain.md). В артефакт вшиты статика
 * фронтенда и исходники встроенных плагинов, и попадают они туда через этот модуль: продакшн-сборка
 * подменяет его сгенерированным, где `artifactPayload` возвращает настоящую нагрузку.
 *
 * Здесь она всегда `undefined`, и это единственный признак режима: **есть нагрузка — это артефакт,
 * нет — это разработка.** Ни переменной окружения, ни флага запуска: и то и другое можно выставить
 * не тем, а нагрузка либо вшита, либо нет.
 *
 * Подмена сделана заменой модуля на сборке, а не генерацией файла в `src`, потому что
 * сгенерированный исходник пришлось бы исключать из линтера, форматтера и проверки типов — то есть
 * из `make check`, который и есть проверка репозитория.
 */

/** Файлы нагрузки: путь → содержимое. Путь всегда с `/`, даже когда сборка шла на Windows. */
export type PayloadFiles = ReadonlyMap<string, Uint8Array>;

export type ArtifactPayload = {
  /**
   * Вывод сборки фронтенда: ключ — путь от корня вывода (`index.html`, `assets/main-a1b2c3.js`).
   * Отдаётся из памяти, каталога со статикой рядом с артефактом не существует вовсе.
   */
  web: PayloadFiles;
  /**
   * Отпечаток содержимого всей нагрузки. Версии платформы для распаковки недостаточно: между
   * двумя сборками артефакта она не меняется, и без отпечатка вторая сборка молча работала бы с
   * содержимым первой (docs/toolchain.md).
   */
  digest: string;
};

export function artifactPayload(): ArtifactPayload | undefined {
  return undefined;
}
